"""Generate DTFlow's bundled logging-component choices from source declarations.

Run explicitly and commit the result after changing logger declarations.
Packaging uses the checked-in catalogue without rewriting source files;
the desktop never scans Python or log files.
"""

from __future__ import annotations

import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "dtflow"
TARGET = SOURCE / "diagnostic_components.py"
# Listener-authored synthetic components are not Python logger declarations.
SYNTHETIC = ("dtflow", "dtflow.diagnostics", "dtflow.ui.gallery_perf", "dtflow.ui.performance")


def discover_components() -> tuple[str, ...]:
    """Collect DTFlow logger names without importing the application or emitting diagnostics."""
    names = set(SYNTHETIC)
    for source in SOURCE.rglob("*.py"):
        if source.name == TARGET.name:
            continue
        module = "dtflow." + ".".join(source.relative_to(SOURCE).with_suffix("").parts)
        if module.endswith(".__init__"):
            module = module.removesuffix(".__init__")
        tree = ast.parse(source.read_text(encoding="utf-8"), filename=str(source))
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
                continue
            if node.func.attr != "getLogger":
                continue
            if not node.args:
                names.add("root")
            elif isinstance(node.args[0], ast.Name) and node.args[0].id == "__name__":
                names.add(module)
            elif isinstance(node.args[0], ast.Constant) and isinstance(node.args[0].value, str):
                names.add(node.args[0].value)
    return tuple(sorted(names))


def generate() -> bool:
    """Write the deterministic catalogue only when logger declarations change."""
    names = discover_components()
    lines = [
        '"""Bundled diagnostic Component choices; generated by tools/generate_diagnostic_components.py."""',
        "",
        "COMPONENTS = (",
        *(f"    {json.dumps(name)}," for name in names),
        ")",
        "",
    ]
    content = "\n".join(lines)
    if TARGET.is_file() and TARGET.read_text(encoding="utf-8") == content:
        return False
    TARGET.write_text(content, encoding="utf-8")
    return True


if __name__ == "__main__":
    print("Updated diagnostic Component catalogue" if generate() else "Diagnostic Component catalogue unchanged")
