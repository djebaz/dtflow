from datetime import datetime, timezone
import json
from pathlib import Path
import re
from urllib.parse import urlsplit
import uuid

_FORM_EMBEDDED_PROJECT_REVISION = ""  # generated by builder

#@markdown Add a Civitai page or download URL. Optional authentication uses Colab Secrets, never a token in this form.
#@markdown The official converter is built from pinned source on Linux. This Colab build path is experimental and has not been exercised end to end.
# The builder replaces this marker from JobConfig and FORM_* metadata.
#@markdown Embedded mode is ready to run. Blank source fields are unused; blank model_version uses upstream auto-detection.
#@markdown ### Project source
#@markdown Embedded is deterministic and works in a fresh runtime. Repository mode requires an immutable 40-character commit SHA. Local mode requires revision `local`.
#@markdown Project namespace: `lora-converter`
project_id = 'lora-converter'
project_source_mode = 'embedded' #@param ["embedded", "repository", "local"]
project_repository_url = '' #@param {type:"string"}
project_revision = '' #@param {type:"string"}
project_subdirectory = '' #@param {type:"string"}
project_source_path = '' #@param {type:"string"}

#@markdown ### Civitai LoRA
input_url = '' #@param {type:"string"}
civitai_secret_name = 'CIVITAI_API_TOKEN' #@param {type:"string"}

#@markdown ### Conversion
model_version = '' #@param {type:"string"}
scale_factor = 1.0 #@param {type:"number"}
build_jobs = 2 #@param {type:"integer"}

#@markdown ### Output
output_name = 'converted_lora.ckpt' #@param {type:"string"}
auto_download = True #@param {type:"boolean"}

#@markdown ### Persistence and execution
persistent_root = '/content/drive/MyDrive/production_colab/lora-converter' #@param {type:"string"}
runtime_root = '/content/production_colab/lora-converter' #@param {type:"string"}
reuse_cache = True #@param {type:"boolean"}

if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", project_id):
    raise ValueError("project_id must use lowercase letters, numbers, and single hyphens")
_repository = urlsplit(project_repository_url) if project_repository_url else None
if _repository and (_repository.username or _repository.password or _repository.query):
    raise ValueError(
        "Do not place credentials or signed query strings in project_repository_url. "
        "Use the runtime's configured Git authentication."
    )
if project_source_mode == "repository" and not re.fullmatch(r"[0-9a-fA-F]{40}", project_revision):
    raise ValueError("Repository mode requires an immutable 40-character commit SHA")
if project_source_mode == "local" and (not project_source_path or project_revision != "local"):
    raise ValueError("Local mode requires project_source_path and project_revision='local'")

_configuration = {
    'project_id': project_id,
    'project_source_mode': project_source_mode,
    'project_repository_url': project_repository_url,
    'project_revision': project_revision,
    'project_subdirectory': project_subdirectory,
    'project_source_path': project_source_path,
    'input_url': input_url,
    'civitai_secret_name': civitai_secret_name,
    'model_version': model_version,
    'scale_factor': scale_factor,
    'build_jobs': build_jobs,
    'output_name': output_name,
    'auto_download': auto_download,
    'persistent_root': persistent_root,
    'runtime_root': runtime_root,
    'reuse_cache': reuse_cache,
}

SUBMITTED_JOB = {
    "policy_revision": "production-colab-v4",
    "submission_id": datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    + "-"
    + uuid.uuid4().hex[:8],
    "submitted_utc": datetime.now(timezone.utc).isoformat(),
    "submitted_project_revision": (
        _FORM_EMBEDDED_PROJECT_REVISION
        if project_source_mode == "embedded"
        else project_revision
    ),
    "configuration": _configuration,
}

PENDING_JOB_PATH = Path(runtime_root).expanduser() / "state" / "pending_job.json"
PENDING_JOB_PATH.parent.mkdir(parents=True, exist_ok=True)
_temporary = PENDING_JOB_PATH.with_suffix(".json.tmp")
_temporary.write_text(
    json.dumps(SUBMITTED_JOB, indent=2, sort_keys=True) + "\n",
    encoding="utf-8",
)
_temporary.replace(PENDING_JOB_PATH)

print("Job configured. Processing has not started.")
print(f"Frozen submission: {PENDING_JOB_PATH}")
print(f"Project source: {project_source_mode}")
print(f"Persistent root: {persistent_root}")
print(f"Final output: /content/outputs/{output_name}")
