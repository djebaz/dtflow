_EMBEDDED_PROJECT_FILES = {}  # generated by builder
_EMBEDDED_PROJECT_REVISION = ""  # generated by builder
_EMBEDDED_PROJECT_ID = 'lora-converter'  # generated
_EMBEDDED_DEFAULT_RUNTIME_ROOT = '/content/production_colab/lora-converter'  # generated
_EMBEDDED_DEFAULT_PERSISTENT_ROOT = '/content/drive/MyDrive/production_colab/lora-converter'  # generated
_URL_RE = re.compile(r"https?://[^\s'\"]+")
_EXECUTION_ID = (
    datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8]
)
_BUNDLE_EXCLUDED_DIRECTORIES = {"__pycache__"}
_BUNDLE_EXCLUDED_SUFFIXES = {".pyc", ".pyo"}


def _atomic_write_json(path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(path)


def _redact_argument(value):
    text = str(value)
    if "://" not in text:
        return text
    parsed = urlsplit(text)
    hostname = parsed.hostname or ""
    if parsed.port:
        hostname += f":{parsed.port}"
    netloc = ("***@" if parsed.username or parsed.password else "") + hostname
    return urlunsplit((parsed.scheme, netloc, parsed.path, "", ""))


def _redact_text(value):
    return _URL_RE.sub(lambda match: _redact_argument(match.group(0)), str(value))


def _start_logs(runtime_root, submission_id, carry_from=None):
    global _BOOTSTRAP_LOG, _RUN_BOOTSTRAP_LOG
    previous_global_log = globals().get("_BOOTSTRAP_LOG")
    carry_text = ""
    if carry_from and Path(carry_from).is_file():
        carry_text = Path(carry_from).read_text(encoding="utf-8")
    runtime_root.mkdir(parents=True, exist_ok=True)
    session_path = runtime_root / ".runtime_session_id"
    if session_path.exists():
        session_id = session_path.read_text(encoding="utf-8").strip()
    else:
        session_id = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ") + "-" + uuid.uuid4().hex[:8]
        session_path.write_text(session_id + "\n", encoding="utf-8")
    log_root = runtime_root / "logs"
    log_root.mkdir(parents=True, exist_ok=True)
    _BOOTSTRAP_LOG = log_root / f"runtime_{session_id}.log"
    _RUN_BOOTSTRAP_LOG = log_root / f"submission_{submission_id}_{_EXECUTION_ID}.log"
    os.environ["COLAB_RUNTIME_LOG"] = str(_BOOTSTRAP_LOG)
    os.environ["COLAB_SUBMISSION_BOOTSTRAP_LOG"] = str(_RUN_BOOTSTRAP_LOG)
    if carry_text and Path(carry_from) != _RUN_BOOTSTRAP_LOG:
        with _RUN_BOOTSTRAP_LOG.open("a", encoding="utf-8") as stream:
            stream.write(carry_text)
        if previous_global_log and Path(previous_global_log) != _BOOTSTRAP_LOG:
            with _BOOTSTRAP_LOG.open("a", encoding="utf-8") as stream:
                stream.write(carry_text)


def _bootstrap_message(message):
    safe = _redact_text(message)
    print(safe, flush=True)
    for path in (_BOOTSTRAP_LOG, _RUN_BOOTSTRAP_LOG):
        with path.open("a", encoding="utf-8") as stream:
            stream.write(safe + "\n")


def _run_bootstrap_command(command):
    _bootstrap_message("COMMAND START: " + " ".join(_redact_argument(item) for item in command))
    started = time.monotonic()
    process = subprocess.Popen(
        [str(item) for item in command],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        bufsize=1,
    )
    assert process.stdout is not None
    for line in process.stdout:
        _bootstrap_message(line.rstrip("\n"))
    return_code = process.wait()
    _bootstrap_message(
        f"COMMAND END: exit_code={return_code} duration_seconds={time.monotonic() - started:.2f}"
    )
    if return_code:
        raise subprocess.CalledProcessError(return_code, command)


def _read_bootstrap_command(command):
    _bootstrap_message("COMMAND START: " + " ".join(_redact_argument(item) for item in command))
    started = time.monotonic()
    process = subprocess.run(
        [str(item) for item in command],
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
    )
    output = process.stdout.rstrip("\n")
    if output:
        for line in output.splitlines():
            _bootstrap_message(line)
    _bootstrap_message(
        f"COMMAND END: exit_code={process.returncode} "
        f"duration_seconds={time.monotonic() - started:.2f}"
    )
    if process.returncode:
        raise subprocess.CalledProcessError(process.returncode, command, output=process.stdout)
    return output


def _project_manifest_files(project_root):
    package_root = project_root / "src" / "project_app"
    files = sorted(
        path
        for path in package_root.rglob("*")
        if path.is_file()
        and not _BUNDLE_EXCLUDED_DIRECTORIES.intersection(
            path.relative_to(package_root).parts
        )
        and path.suffix not in _BUNDLE_EXCLUDED_SUFFIXES
    )
    lock = project_root / "requirements.lock"
    if lock.exists():
        files.append(lock)
    return sorted(files, key=lambda path: str(path.relative_to(project_root)))


def _project_tree_fingerprint(project_root):
    digest = hashlib.sha256()
    for path in _project_manifest_files(project_root):
        digest.update(str(path.relative_to(project_root)).encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()


def _materialize_embedded_project(configuration):
    if not _EMBEDDED_PROJECT_FILES or not _EMBEDDED_PROJECT_REVISION:
        raise RuntimeError("This source cell has no embedded project bundle; rebuild the notebook")
    runtime_root = Path(configuration["runtime_root"]).expanduser()
    project_root = runtime_root / "embedded_project" / _EMBEDDED_PROJECT_REVISION[:16]
    resolved_project_root = project_root.resolve()
    for relative, encoded in _EMBEDDED_PROJECT_FILES.items():
        relative_path = PurePosixPath(relative)
        if relative_path.is_absolute() or ".." in relative_path.parts:
            raise RuntimeError(f"Unsafe embedded project path: {relative}")
        destination = project_root.joinpath(*relative_path.parts)
        try:
            destination.resolve().relative_to(resolved_project_root)
        except ValueError as error:
            raise RuntimeError(f"Embedded project path escapes its isolated root: {relative}") from error
        destination.parent.mkdir(parents=True, exist_ok=True)
        try:
            content = base64.b64decode(encoded, validate=True)
        except (ValueError, TypeError) as error:
            raise RuntimeError(f"Embedded project file is not valid base64: {relative}") from error
        if not destination.exists() or destination.read_bytes() != content:
            temporary = destination.with_suffix(destination.suffix + ".tmp")
            temporary.write_bytes(content)
            temporary.replace(destination)
    if _project_tree_fingerprint(project_root) != _EMBEDDED_PROJECT_REVISION:
        raise RuntimeError("Embedded project materialization failed its content fingerprint")
    os.environ["COLAB_PROJECT_RESOLVED_REVISION"] = _EMBEDDED_PROJECT_REVISION
    _bootstrap_message(f"Embedded project restored: {_EMBEDDED_PROJECT_REVISION}")
    return project_root


def _restore_local_project(configuration):
    if configuration.get("project_revision") != "local":
        raise RuntimeError("Local source mode requires project_revision='local'")
    project_root = Path(configuration.get("project_source_path", "")).expanduser().resolve()
    if not (project_root / "src" / "project_app").is_dir():
        raise RuntimeError(f"Local project package is missing: {project_root}")
    resolved = "local-" + _project_tree_fingerprint(project_root)
    os.environ["COLAB_PROJECT_RESOLVED_REVISION"] = resolved
    _bootstrap_message(f"Explicit local project reused: {project_root} ({resolved})")
    return project_root


def _normalized_repository_url(value):
    return value.rstrip("/").removesuffix(".git")


def _restore_repository_project(configuration):
    repository_url = configuration.get("project_repository_url", "").strip()
    revision = configuration.get("project_revision", "").strip().lower()
    if not repository_url or not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise RuntimeError("Repository mode requires a URL and immutable 40-character commit SHA")
    identity = hashlib.sha256((repository_url + "\0" + revision).encode("utf-8")).hexdigest()[:20]
    checkout_root = Path(configuration["runtime_root"]).expanduser() / "project_checkouts" / identity
    if (checkout_root / ".git").is_dir():
        actual_remote = _read_bootstrap_command(
            ["git", "-C", checkout_root, "remote", "get-url", "origin"]
        ).strip()
        if _normalized_repository_url(actual_remote) != _normalized_repository_url(repository_url):
            raise RuntimeError("Existing isolated checkout has an unexpected origin URL")
        actual_head = _read_bootstrap_command(
            ["git", "-C", checkout_root, "rev-parse", "HEAD"]
        ).strip().lower()
        dirty = _read_bootstrap_command(
            ["git", "-C", checkout_root, "status", "--porcelain"]
        ).strip()
        if actual_head == revision and not dirty:
            os.environ["COLAB_PROJECT_RESOLVED_REVISION"] = revision
            _bootstrap_message(f"Pinned repository checkout reused: {revision}")
            return (checkout_root / configuration.get("project_subdirectory", "")).resolve()
    elif checkout_root.exists() and any(checkout_root.iterdir()):
        raise RuntimeError(f"Refusing to replace non-repository checkout: {checkout_root}")
    else:
        checkout_root.parent.mkdir(parents=True, exist_ok=True)
        _run_bootstrap_command(
            ["git", "clone", "--filter=blob:none", "--no-checkout", repository_url, checkout_root]
        )
    _run_bootstrap_command(["git", "-C", checkout_root, "fetch", "--depth", "1", "origin", revision])
    _run_bootstrap_command(["git", "-C", checkout_root, "checkout", "--detach", "--force", revision])
    actual_head = _read_bootstrap_command(
        ["git", "-C", checkout_root, "rev-parse", "HEAD"]
    ).strip().lower()
    if actual_head != revision:
        raise RuntimeError(f"Restored commit {actual_head} does not match submitted commit {revision}")
    dirty = _read_bootstrap_command(
        ["git", "-C", checkout_root, "status", "--porcelain"]
    ).strip()
    if dirty:
        raise RuntimeError("Pinned repository checkout is not clean after restoration")
    project_root = (checkout_root / configuration.get("project_subdirectory", "")).resolve()
    try:
        project_root.relative_to(checkout_root.resolve())
    except ValueError as error:
        raise RuntimeError("project_subdirectory resolves outside the pinned checkout") from error
    if not (project_root / "src" / "project_app").is_dir():
        raise RuntimeError(f"Pinned revision does not contain the project package: {project_root}")
    os.environ["COLAB_PROJECT_RESOLVED_REVISION"] = revision
    _bootstrap_message(f"Pinned repository restored: {_redact_argument(repository_url)}@{revision}")
    return project_root


def _restore_project(snapshot):
    configuration = snapshot["configuration"]
    subdirectory = PurePosixPath(configuration.get("project_subdirectory", "") or ".")
    if subdirectory.is_absolute() or ".." in subdirectory.parts:
        raise RuntimeError("project_subdirectory must be a safe relative path")
    mode = configuration.get("project_source_mode")
    if mode == "embedded":
        return _materialize_embedded_project(configuration)
    if mode == "local":
        return _restore_local_project(configuration)
    if mode == "repository":
        return _restore_repository_project(configuration)
    raise RuntimeError(f"Unsupported project_source_mode: {mode}")


def _mount_drive_if_needed():
    try:
        from google.colab import drive  # type: ignore[import-not-found]
    except ImportError:
        return
    if not Path("/content/drive/MyDrive").is_dir():
        _bootstrap_message("STAGE START: MOUNT_PERSISTENT_STORAGE")
        drive.mount("/content/drive")
        _bootstrap_message("STAGE COMPLETE: MOUNT_PERSISTENT_STORAGE")


def _restore_persistent_pending(runtime_pending):
    _mount_drive_if_needed()
    registry_path = Path("/content/drive/MyDrive/production_colab_registry") / (
        _EMBEDDED_PROJECT_ID + ".json"
    )
    persistent_root = Path(_EMBEDDED_DEFAULT_PERSISTENT_ROOT)
    if registry_path.is_file():
        registry = json.loads(registry_path.read_text(encoding="utf-8"))
        if registry.get("project_id") == _EMBEDDED_PROJECT_ID and registry.get("persistent_root"):
            persistent_root = Path(registry["persistent_root"])
    persistent_pending = persistent_root / "state" / "pending_job.json"
    if not persistent_pending.is_file():
        raise RuntimeError(
            "No frozen job was found in runtime or registered persistent state. "
            "Run the configuration form once, then Run again."
        )
    runtime_pending.parent.mkdir(parents=True, exist_ok=True)
    temporary = runtime_pending.with_suffix(".json.tmp")
    shutil.copy2(persistent_pending, temporary)
    temporary.replace(runtime_pending)
    _bootstrap_message(f"Frozen job restored: {persistent_pending}")
    return json.loads(runtime_pending.read_text(encoding="utf-8"))


def _write_bootstrap_failure(stage, error, snapshot):
    payload = {
        "status": "FAILED",
        "stage": stage,
        "failed_utc": datetime.now(timezone.utc).isoformat(),
        "error": repr(error),
        "traceback": traceback.format_exc(),
        "global_log": str(_BOOTSTRAP_LOG),
        "submission_log": str(_RUN_BOOTSTRAP_LOG),
    }
    if snapshot:
        payload["submission_id"] = snapshot.get("submission_id")
    runtime_failure = _BOOTSTRAP_LOG.parent.parent / "state" / "bootstrap_failure.json"
    try:
        _atomic_write_json(runtime_failure, payload)
    except OSError:
        pass
    if snapshot:
        persistent_root = Path(snapshot.get("configuration", {}).get("persistent_root", ""))
        if persistent_root.exists():
            try:
                _atomic_write_json(persistent_root / "state" / "bootstrap_failure.json", payload)
            except OSError:
                pass


def _execute_submitted_job():
    stage = "LOAD_SUBMITTED_JOB"
    snapshot = None
    pending_default = Path(_EMBEDDED_DEFAULT_RUNTIME_ROOT) / "state" / "pending_job.json"
    pending_path = Path(globals().get("PENDING_JOB_PATH", pending_default))
    try:
        if pending_path.is_file():
            snapshot = json.loads(pending_path.read_text(encoding="utf-8"))
        else:
            _bootstrap_message("No runtime pending job; checking registered persistent state.")
            snapshot = _restore_persistent_pending(pending_path)

        if snapshot.get("configuration", {}).get("project_id") != _EMBEDDED_PROJECT_ID:
            raise RuntimeError(
                "Frozen job project identity does not match this generated notebook"
            )

        configuration = snapshot.get("configuration", {})
        source_mode = configuration.get("project_source_mode")
        submitted_revision = snapshot.get("submitted_project_revision")
        expected_revision = (
            _EMBEDDED_PROJECT_REVISION
            if source_mode == "embedded"
            else configuration.get("project_revision")
        )
        if submitted_revision != expected_revision:
            raise RuntimeError(
                "Frozen job source revision does not match this notebook/project selection"
            )

        recovery_log = _RUN_BOOTSTRAP_LOG
        _start_logs(
            Path(snapshot["configuration"]["runtime_root"]).expanduser(),
            snapshot.get("submission_id", "unknown-submission"),
            carry_from=recovery_log,
        )

        stage = "RESTORE_PROJECT"
        _bootstrap_message("STAGE START: RESTORE_PROJECT")
        project_root = _restore_project(snapshot)
        _bootstrap_message("STAGE COMPLETE: RESTORE_PROJECT")

        source_root = project_root / "src"
        existing = sys.modules.get("project_app")
        if existing is not None and (
            source_mode == "local"
            or not str(getattr(existing, "__file__", "")).startswith(str(source_root))
        ):
            for name in [name for name in sys.modules if name == "project_app" or name.startswith("project_app.")]:
                del sys.modules[name]
        if str(source_root) not in sys.path:
            sys.path.insert(0, str(source_root))

        stage = "VALIDATE_SUBMITTED_JOB"
        from project_app.config import load_pending_job
        from project_app.orchestrator import run_complete_job
        from project_app.results import show_result_panel

        config, validated_snapshot = load_pending_job(pending_path)
        stage = "RUN_COMPLETE_JOB"
        run_result = run_complete_job(
            config,
            project_root,
            submitted_job=validated_snapshot,
        )
        stage = "DELIVER_RESULT"
        delivery_result = show_result_panel(run_result, auto_download=config.auto_download)
        return project_root, config, validated_snapshot, run_result, delivery_result
    except BaseException as exc:
        _bootstrap_message(f"BOOTSTRAP FAILED: stage={stage} error={exc!r}")
        _bootstrap_message(traceback.format_exc())
        _write_bootstrap_failure(stage, exc, snapshot)
        raise


_start_logs(
    Path(os.environ.get("COLAB_RUNTIME_ROOT", _EMBEDDED_DEFAULT_RUNTIME_ROOT)),
    "recovery-"
    + datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    + "-"
    + uuid.uuid4().hex[:8],
)
PROJECT_ROOT, CONFIG, SUBMITTED_JOB, RUN_RESULT, DELIVERY_RESULT = _execute_submitted_job()
